import * as fs from 'node:fs';
import * as path from 'node:path';

import type { ProductCategoryTreeNode } from './covetrus-product-category-tree';

const RELATIVE_OBJECT_PATH =
  'packages/shared/src/catalogue/product-category.ts';

export function resolveProductCategoryObjectFilePath(
  cwd: string = process.cwd(),
): string {
  const candidates = [
    path.resolve(cwd, RELATIVE_OBJECT_PATH),
    path.resolve(cwd, '..', '..', RELATIVE_OBJECT_PATH),
  ];

  for (const candidate of candidates) {
    if (fs.existsSync(path.dirname(candidate))) {
      return candidate;
    }
  }

  throw new Error(
    `Could not resolve ${RELATIVE_OBJECT_PATH} from cwd=${cwd}; run the API from the monorepo (apps/server or repo root).`,
  );
}

export function renderProductCategoryObjectFile(
  forest: ProductCategoryTreeNode[],
): string {
  const bodyLines = renderForestLines(forest, 1);

  return [
    '/** Generated by POST system/jobs/covetrus/scrape-product-categories — prefer regenerating over hand-edits. */',
    'export const ProductCategory = {',
    ...bodyLines,
    '} as const;',
    '',
    'export type ProductCategoryTree = typeof ProductCategory;',
    '',
  ].join('\n');
}

export async function writeProductCategoryObjectFile(
  filePath: string,
  forest: ProductCategoryTreeNode[],
): Promise<void> {
  await fs.promises.writeFile(
    filePath,
    renderProductCategoryObjectFile(forest),
    'utf8',
  );
}

export function toProductCategoryObjectKey(label: string): string {
  const parts = label
    .replace(/['’]/g, '')
    .split(/[^A-Za-z0-9]+/)
    .filter((part) => part.length > 0);

  if (parts.length === 0) {
    return 'unknown';
  }

  const [first, ...rest] = parts;
  const key = first!.toLowerCase() + rest.map(toPascalIdentifierPart).join('');
  if (/^\d/.test(key)) {
    return `cat${key}`;
  }
  return key;
}

function renderForestLines(
  nodes: ProductCategoryTreeNode[],
  indent: number,
): string[] {
  const pad = '  '.repeat(indent);
  const usedKeys = new Set<string>();
  const lines: string[] = [];

  for (const node of nodes) {
    const key = allocateUniqueKey(
      toProductCategoryObjectKey(node.label),
      usedKeys,
    );
    usedKeys.add(key);

    if (node.children.length === 0) {
      lines.push(`${pad}${key}: ${JSON.stringify(node.label)},`);
      continue;
    }

    lines.push(`${pad}${key}: {`);
    lines.push(...renderForestLines(node.children, indent + 1));
    lines.push(`${pad}},`);
  }

  return lines;
}

function toPascalIdentifierPart(part: string): string {
  if (part.length > 1 && part === part.toUpperCase() && /[A-Z]/.test(part)) {
    return part;
  }
  return part.charAt(0).toUpperCase() + part.slice(1);
}

function allocateUniqueKey(baseKey: string, usedKeys: Set<string>): string {
  if (!usedKeys.has(baseKey)) {
    return baseKey;
  }

  let suffix = 2;
  while (usedKeys.has(`${baseKey}${suffix}`)) {
    suffix += 1;
  }
  return `${baseKey}${suffix}`;
}
